"""SUMMARY.md for one catalog-regression run directory (generated; never hand-edited).

    uv run python tools/regression/summarize.py data/regression/<wheel>/<date> \\
        [--prev data/regression/<older wheel>/<date>] [--bundles <bundles.json>]

Reads every `<bundle_id>.json` in the run directory and writes
`<run-dir>/SUMMARY.md`: a header (wheel, date, host, suite, bundle count by
role, status totals over every bundle and over the chat bundles only), one
table row per bundle with one P / F / N cell per check (F and N carry a
footnote number), one footnote line per FAIL / NA (check id, reason, the
first 80 characters of the answer), and with `--prev` a diff section against
an earlier run (new FAIL / fixed / unchanged / not run).
When the run re-ran its FAIL checks (`run_regression.py --retry-fails`), a
cell whose status differs from an earlier attempt's is flaky: it carries a
`*`, the header counts them, and a Flaky section lists each one with the
statuses of its attempts in order.
A bundle's role is its row's `role` in the bundle list (`--bundles`, default
`data/regression/bundles.json`; tools/regression/roles.py). A bundle that is
not a chat model runs the same checks, but suite v1 does not apply to it: its
table row and footnotes name its role and the FAIL and NA section subtotals
by role. A bundle the list does not name is chat, and so is every bundle when
the list is absent (one warning on stderr).
The output depends on the JSON files and those roles only, so a re-run
reproduces it byte for byte; tests/test_regression.py holds every committed
SUMMARY.md to that.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import roles  # noqa: E402 - stdlib only; the role vocabulary and its default

REPO_ROOT = Path(__file__).resolve().parents[2]
BUNDLES = REPO_ROOT / "data" / "regression" / "bundles.json"
SUITE_V1 = (
    "describe", "plain_paris", "digit_default_1", "digit_default_2", "digit_default_3",
    "digit_default_uncapped", "digit_think_off", "digit_think_on", "tool_call_auto",
    "engine_shared_2conv", "two_turn_memory", "digit_gpu_default", "cpu_gpu_match",
)
SHORT = {
    "describe": "desc", "plain_paris": "paris", "digit_default_1": "d1",
    "digit_default_2": "d2", "digit_default_3": "d3", "digit_default_uncapped": "d-unc",
    "digit_think_off": "d-off", "digit_think_on": "d-on", "tool_call_auto": "tool",
    "engine_shared_2conv": "eng2", "two_turn_memory": "mem", "digit_gpu_default": "gpu",
    "cpu_gpu_match": "c=g",
}
LETTER = {"PASS": "P", "FAIL": "F", "NA": "N"}
MARKER = "<!-- generated by tools/regression/summarize.py"


def load_run(run_dir: Path) -> dict[str, dict[str, Any]]:
    docs = {}
    for path in sorted(run_dir.glob("*.json")):
        doc = json.loads(path.read_text(encoding="utf-8"))
        docs[doc["bundle_id"]] = doc
    return docs


def load_roles(bundles: Path) -> dict[str, str]:
    """bundle_id -> role from the bundle list; {} (every bundle chat) when the
    list is absent."""
    if not bundles.is_file():
        print(f"warning: {rel(bundles)} not found; every bundle counted as {roles.DEFAULT}",
              file=sys.stderr)
        return {}
    rows = json.loads(bundles.read_text(encoding="utf-8"))["bundles"]
    return {r["bundle_id"]: r.get("role") or roles.DEFAULT for r in rows}


def role_order(role: str) -> tuple[int, str]:
    return (roles.VALUES.index(role) if role in roles.VALUES else len(roles.VALUES), role)


def rel(path: Path) -> str:
    path = path.resolve()
    try:
        return str(path.relative_to(REPO_ROOT))
    except ValueError:
        return str(path)


def one_line(text: str, n: int) -> str:
    return json.dumps(" ".join(text.split())[:n], ensure_ascii=False)


def attempts(rec: dict[str, Any]) -> list[dict[str, Any]]:
    """Earlier attempts of a re-run check, oldest first."""
    return (rec.get("details") or {}).get("previous_attempts") or []


def flaky(rec: dict[str, Any]) -> bool:
    return any(a.get("status") != rec["status"] for a in attempts(rec))


def label(rec: dict[str, Any]) -> str:
    return f"{rec['status']} {rec['reason']}".strip()


def render(run_dir: Path, prev_dir: Path | None = None, bundles: Path | None = None) -> str:
    docs = load_run(run_dir)
    listed = load_roles(bundles or BUNDLES)
    role = {bid: listed.get(bid, roles.DEFAULT) for bid in docs}
    name = {bid: bid + (f" ({r})" if r != roles.DEFAULT else "") for bid, r in role.items()}
    lines = [f"{MARKER} from {rel(run_dir)}"
             + (f" --prev {rel(prev_dir)}" if prev_dir else "")
             + (f" --bundles {rel(bundles)}" if bundles and bundles.resolve() != BUNDLES else "")
             + "; do not edit -->"]
    envs = sorted({(d["env"]["runtime_version"], d["env"]["host"], d["env"]["os"],
                    d["env"]["python"]) for d in docs.values()})
    dates = sorted({d["date"] for d in docs.values()})
    suites = sorted({d["suite"] for d in docs.values()})
    totals = {"PASS": 0, "FAIL": 0, "NA": 0}
    by_role: dict[str, Counter[str]] = {}
    rerun: list[tuple[str, dict[str, Any]]] = []
    for bid, doc in sorted(docs.items()):
        tally = by_role.setdefault(role[bid], Counter())
        for check in doc["checks"]:
            totals[check["status"]] += 1
            tally[check["status"]] += 1
            if attempts(check):
                rerun.append((bid, check))
    flaky_cells = [(bid, rec) for bid, rec in rerun if flaky(rec)]
    wheel = ", ".join(sorted({e[0] for e in envs})) or run_dir.parent.name
    chat = by_role.get(roles.DEFAULT, Counter())
    n_chat = sum(r == roles.DEFAULT for r in role.values())
    others = Counter(r for r in role.values() if r != roles.DEFAULT)
    other_text = ", ".join(f"{r} {others[r]}" for r in sorted(others, key=role_order))
    lines += [
        f"# Catalog regression: litert-lm {wheel}, {', '.join(dates) or run_dir.name}",
        "",
        "- host: " + ("; ".join(f"{h} (macOS {o}, Python {p})" for _, h, o, p in envs)
                      or "-"),
        f"- suite: {', '.join(suites) or '-'} ({len(SUITE_V1)} checks, each in a fresh "
        "process; tools/regression/README.md)",
        f"- bundles: {len(docs)} (chat {n_chat} / non-chat {len(docs) - n_chat}"
        + (f": {other_text}" if others else "") + ")",
        f"- checks: {totals['PASS']} PASS / {totals['FAIL']} FAIL / {totals['NA']} NA"
        + (f"; flaky {len(flaky_cells)}" if rerun else ""),
        f"- checks (chat bundles only): {chat['PASS']} PASS / {chat['FAIL']} FAIL / "
        f"{chat['NA']} NA",
        "",
        "Columns: " + ", ".join(f"{SHORT[c]} = {c}" for c in SUITE_V1) + "."
        + (" * = flaky (the one re-run of a FAIL changed its status)." if rerun else "")
        + (" (role) after a bundle = not a chat model (bundles.json `role`): suite v1 does "
           "not apply to it, so it stays out of the chat-only totals." if others else ""),
        "",
        "| bundle | " + " | ".join(SHORT[c] for c in SUITE_V1) + " |",
        "|---|" + "---|" * len(SUITE_V1),
    ]
    notes: list[str] = []
    for bid, doc in sorted(docs.items()):
        by_id = {c["id"]: c for c in doc["checks"]}
        cells = []
        for check in SUITE_V1:
            rec = by_id.get(check)
            if rec is None:
                cells.append("-")
                continue
            cell = LETTER[rec["status"]] + ("*" if flaky(rec) else "")
            if rec["status"] != "PASS":
                notes.append(f"- [{len(notes) + 1}] {name[bid]} {check}: {rec['status']} "
                             f"{rec['reason']}; raw_head {one_line(rec['raw_head'], 80)}")
                cell += f" [{len(notes)}]"
            cells.append(cell)
        lines.append(f"| {name[bid]} | " + " | ".join(cells) + " |")
    lines += ["", "## FAIL and NA", ""]
    if notes and others:
        lines += ["By role: " + "; ".join(
            f"{r} {by_role[r]['FAIL']} FAIL / {by_role[r]['NA']} NA"
            for r in sorted(by_role, key=role_order)) + ".", ""]
    lines += notes or ["(none)"]
    if rerun:
        lines += ["", "## Flaky", "",
                  f"FAIL checks re-run once: {len(rerun)}; status changed: {len(flaky_cells)}.",
                  ""]
        lines += [f"- {bid} {rec['id']}: " + " -> ".join(
            [label(a) for a in attempts(rec)] + [label(rec)]) for bid, rec in flaky_cells]
        lines += [] if flaky_cells else ["(none)"]
    if prev_dir is not None:
        lines += ["", *diff_section(load_run(prev_dir), docs, prev_dir)]
    return "\n".join(lines) + "\n"


def diff_section(prev: dict[str, dict[str, Any]], now: dict[str, dict[str, Any]],
                 prev_dir: Path) -> list[str]:
    def statuses(docs: dict[str, dict[str, Any]]) -> dict[tuple[str, str], dict[str, Any]]:
        return {(bid, c["id"]): c for bid, doc in docs.items() for c in doc["checks"]}

    before, after = statuses(prev), statuses(now)
    new_fail, fixed, unchanged, not_run = [], [], 0, []
    for key in sorted(set(before) | set(after)):
        b, a = before.get(key), after.get(key)
        label = f"{key[0]} {key[1]}"
        if a is None or a["status"] == "NA":
            if b is not None and b["status"] != "NA":
                why = "absent" if a is None else f"NA {a['reason']}"
                not_run.append(f"- {label}: {b['status']} -> {why}")
            elif b is not None:
                unchanged += 1
            continue
        if a["status"] == "FAIL" and (b is None or b["status"] != "FAIL"):
            was = "absent" if b is None else b["status"]
            new_fail.append(f"- {label}: {was} -> FAIL {a['reason']}; raw_head "
                            f"{one_line(a['raw_head'], 80)}")
        elif a["status"] == "PASS" and b is not None and b["status"] == "FAIL":
            fixed.append(f"- {label}: FAIL {b['reason']} -> PASS")
        elif b is not None and b["status"] == a["status"]:
            unchanged += 1
    out = [f"## Diff against {rel(prev_dir)}", "",
           f"new FAIL: {len(new_fail)}; fixed: {len(fixed)}; unchanged: {unchanged}; "
           f"not run now: {len(not_run)}", ""]
    for title, items in (("New FAIL", new_fail), ("Fixed", fixed), ("Not run now", not_run)):
        out += [f"### {title}", "", *(items or ["(none)"]), ""]
    return out[:-1]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("run_dir")
    ap.add_argument("--prev", default=None)
    ap.add_argument("--bundles", default=None)
    args = ap.parse_args(argv)
    run_dir = Path(args.run_dir)
    prev = Path(args.prev) if args.prev else None
    text = render(run_dir, prev, Path(args.bundles) if args.bundles else None)
    (run_dir / "SUMMARY.md").write_text(text, encoding="utf-8")
    print(f"wrote {run_dir / 'SUMMARY.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
